      <h2>Fitnessstudio kündigen – was Sie wissen müssen</h2>
      <p>Fitnessverträge weisen in Deutschland typischerweise eine Mindestlaufzeit von 12 oder 24 Monaten auf. Eine nicht fristgerechte Kündigung führte in der Vergangenheit oft zu einer ungewollten automatischen Verlängerung.</p>
      <p>Seit dem <strong>Gesetz für faire Verbraucherverträge</strong> (gültig ab 1. März 2022) hat sich dies zugunsten der Verbraucher geändert:</p>
      <ul style="margin: 0 0 20px 20px; padding: 0; color: var(--muted, #475569); line-height: 1.8; font-size: 16px;">
        <li style="margin-bottom: 8px;"><strong>Nach der Erstlaufzeit</strong> verlängern sich Verträge nur noch auf unbestimmte Zeit.</li>
        <li style="margin-bottom: 8px;">Sie profitieren von einer monatlichen Kündbarkeit mit einer Frist von <strong>maximal einem Monat</strong>.</li>
        <li>Starre Jahresverlängerungen sind rechtlich unzulässig.</li>
      </ul>
      <p><strong>Für Altverträge (vor März 2022):</strong> Zum Ende der Erstlaufzeit kann noch eine Kündigungsfrist von bis zu drei Monaten gelten. Nach der ersten Verlängerungsperiode greift jedoch auch hier das neue Gesetz zur monatlichen Kündbarkeit.</p>
