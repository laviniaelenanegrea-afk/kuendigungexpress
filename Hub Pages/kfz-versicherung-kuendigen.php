<h2 id="intro-title">KFZ-Versicherung kündigen – was Sie wissen müssen</h2>
<p>
Im Gegensatz zu Handy- oder Fitnessverträgen fallen KFZ-Versicherungen <strong>nicht</strong> unter das neue Verbraucherschutzgesetz, das monatliche Kündigungen nach Ablauf der Mindestlaufzeit erlaubt. KFZ-Policen verlängern sich in Deutschland in der Regel automatisch um ein <strong>volles weiteres Jahr</strong>, wenn Sie nicht fristgerecht kündigen.
