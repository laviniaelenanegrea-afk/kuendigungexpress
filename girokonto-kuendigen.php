  <p>Die meisten Banken schließen ein Konto erst, wenn der Saldo bei 0,00 € liegt. Gehen Sie deshalb in dieser Reihenfolge vor:</p>
  <ul style="margin: 0 0 20px 20px; padding: 0; color: var(--muted, #475569); line-height: 1.8; font-size: 16px;">
    <li style="margin-bottom: 8px;"><strong>Neues Konto zuerst eröffnen:</strong> Kündigen Sie erst, wenn Ihr neues Girokonto einsatzbereit ist.</li>
    <li style="margin-bottom: 8px;"><strong>Dispo ausgleichen:</strong> Ist das Konto im Minus, gleichen Sie den Betrag inklusive anteiliger Zinsen aus. Manche Banken rechnen den Dispo quartalsweise ab.</li>
    <li style="margin-bottom: 8px;"><strong>Restguthaben-Ziel angeben:</strong> Nennen Sie im Schreiben die IBAN, auf die Ihr Guthaben überwiesen werden soll.</li>
    <li><strong>Freistellungsauftrag löschen:</strong> Sonst endet er automatisch – geben Sie ihn ggf. bei Ihrer neuen Bank neu an.</li>
