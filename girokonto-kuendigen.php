<h2 id="intro-title">Girokonto kündigen – was Sie wissen müssen</h2>
<p>Ihr Girokonto können Sie <strong>jederzeit und ohne Einhaltung einer Frist</strong> kündigen. Das regelt § 675h BGB. Anders als bei einem Miet- oder Arbeitsvertrag ist dafür keine handschriftliche Unterschrift gesetzlich vorgeschrieben – die <strong>Textform</strong> genügt. Ein sauberes, schriftliches Kündigungsschreiben mit Zugangsnachweis ist trotzdem der sicherste Weg, weil Sie damit im Streitfall belegen können, wann Ihre Kündigung bei der Bank eingegangen ist.</p>
<p>Wichtig ist vor allem, was <em>rund um</em> die Kündigung passiert: Ihr Restguthaben muss auf ein neues Konto überwiesen, ein möglicher Dispo ausgeglichen und laufende Zahlungen umgezogen werden. Unser kostenloses PDF enthält bereits die passenden Formulierungen – inklusive Bitte um Überweisung des Restguthabens und um eine schriftliche Bestätigung.</p>
